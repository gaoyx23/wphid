"""Literature-grounded reusable-launch-vehicle hot-structure truth model.

The model represents an SiC-protected RCC/C-SiC hot structure during an
atmospheric-entry heating cycle.  It is deliberately a reduced-order research
benchmark, not a flight-certification model.  Unlike the manufactured fields
used by the early discovery tests, all state fields here are generated by
forward integration of conservation laws.

The three state variables are temperature ``T`` [K], normalized oxidant
activity ``O`` [-], and normalized carbon-consumption damage ``D`` [-].  The
same hidden nonlinear oxidation rate enters the energy, oxidant, and damage
balances.  Damage also changes conductivity and gas diffusivity, producing a
closed thermo-chemo-damage feedback loop.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from types import MappingProxyType
from typing import Mapping

import numpy as np


_STEFAN_BOLTZMANN = 5.670374419e-8
_GAS_CONSTANT = 8.314462618


@dataclass(frozen=True)
class TPSMaterial:
    """Effective C/C-SiC properties for a plate-like hot structure."""

    density: float = 1900.0
    heat_capacity_ambient: float = 1000.0
    heat_capacity_hot: float = 1800.0
    conductivity_axial: float = 18.0
    conductivity_through: float = 9.0
    emissivity: float = 0.85
    conductivity_damage_loss: float = 0.35


@dataclass(frozen=True)
class TPSOxidation:
    """Reduced porous-transport and carbon-oxidation parameters."""

    activation_energy: float = 123_000.0
    pre_exponential: float = 0.12
    oxygen_exponent: float = 1.0
    remaining_carbon_exponent: float = 1.0
    oxidant_diffusivity: float = 8.0e-7
    damage_diffusivity_gain: float = 12.0
    surface_mass_transfer: float = 2.0e-4
    oxidant_consumption: float = 0.18
    reaction_heat_per_damage: float = 2.5e8


@dataclass(frozen=True)
class TPSMission:
    """Natural entry-duty-cycle inputs rather than imposed state perturbations."""

    duration: float = 900.0
    peak_time: float = 500.0
    heat_width: float = 165.0
    peak_heat_flux: float = 600_000.0
    oxidant_width: float = 205.0
    peak_oxidant_activity: float = 1.0
    hotspot_location: float = 0.55
    hotspot_width: float = 0.18
    ambient_temperature: float = 230.0
    support_temperature: float = 330.0
    back_heat_transfer: float = 18.0


@dataclass(frozen=True)
class TPSGrid:
    """Cell-centred axial/through-thickness grid and integration settings."""

    axial_length: float = 0.60
    thickness: float = 0.006
    axial_cells: int = 21
    thickness_cells: int = 12
    time_step: float = 0.02
    output_interval: float = 5.0


@dataclass(frozen=True)
class TPSFieldTrajectory:
    """Observation-facing fields from one simulated mission."""

    t: np.ndarray
    z: np.ndarray
    x: np.ndarray
    states: Mapping[str, np.ndarray]
    loads: Mapping[str, np.ndarray]
    mission_id: str

    def __post_init__(self) -> None:
        time = _readonly(self.t)
        axial = _readonly(self.z)
        depth = _readonly(self.x)
        if time.ndim != 1 or axial.ndim != 1 or depth.ndim != 1:
            raise ValueError("t, z, and x must be one-dimensional")
        expected = (time.size, axial.size, depth.size)
        states = {}
        for name, values in self.states.items():
            array = _readonly(values)
            if array.shape != expected:
                raise ValueError(f"state {name!r} must have shape {expected}")
            states[name] = array
        loads = {}
        for name, values in self.loads.items():
            array = _readonly(values)
            if array.shape[0] != time.size:
                raise ValueError(f"load {name!r} must match the time axis")
            loads[name] = array
        object.__setattr__(self, "t", time)
        object.__setattr__(self, "z", axial)
        object.__setattr__(self, "x", depth)
        object.__setattr__(self, "states", MappingProxyType(states))
        object.__setattr__(self, "loads", MappingProxyType(loads))


def simulate_reusable_tps_mission(
    mission_id: str,
    *,
    mission: TPSMission | None = None,
    material: TPSMaterial | None = None,
    oxidation: TPSOxidation | None = None,
    grid: TPSGrid | None = None,
    initial_damage: float | np.ndarray = 0.0,
) -> TPSFieldTrajectory:
    """Integrate a coupled heat/oxidant/damage mission from conservation laws."""

    if not isinstance(mission_id, str) or not mission_id:
        raise ValueError("mission_id must be a non-empty string")
    mission = TPSMission() if mission is None else mission
    material = TPSMaterial() if material is None else material
    oxidation = TPSOxidation() if oxidation is None else oxidation
    grid = TPSGrid() if grid is None else grid
    _validate_configuration(mission, material, oxidation, grid)

    dz = grid.axial_length / grid.axial_cells
    dx = grid.thickness / grid.thickness_cells
    z = (np.arange(grid.axial_cells, dtype=float) + 0.5) * dz
    x = (np.arange(grid.thickness_cells, dtype=float) + 0.5) * dx
    steps = int(round(mission.duration / grid.time_step))
    if not np.isclose(steps * grid.time_step, mission.duration):
        raise ValueError("duration must be an integer multiple of time_step")
    output_stride = int(round(grid.output_interval / grid.time_step))
    if not np.isclose(output_stride * grid.time_step, grid.output_interval):
        raise ValueError("output_interval must be an integer multiple of time_step")

    shape = (grid.axial_cells, grid.thickness_cells)
    temperature = np.full(shape, mission.support_temperature, dtype=float)
    oxidant = np.zeros(shape, dtype=float)
    damage = _initial_damage_field(initial_damage, shape)

    output_steps = np.arange(0, steps + 1, output_stride, dtype=int)
    if output_steps[-1] != steps:
        output_steps = np.append(output_steps, steps)
    times = output_steps.astype(float) * grid.time_step
    state_history = {
        "T": np.empty((times.size, *shape), dtype=float),
        "O": np.empty((times.size, *shape), dtype=float),
        "D": np.empty((times.size, *shape), dtype=float),
    }
    surface_heat_history = np.empty((times.size, grid.axial_cells), dtype=float)
    external_oxidant_history = np.empty(times.size, dtype=float)

    output_index = 0
    for step in range(steps + 1):
        time_value = step * grid.time_step
        if step == output_steps[output_index]:
            state_history["T"][output_index] = temperature
            state_history["O"][output_index] = oxidant
            state_history["D"][output_index] = damage
            surface_heat_history[output_index] = _surface_heat_flux(
                time_value, z, mission, grid
            )
            external_oxidant_history[output_index] = _external_oxidant(
                time_value, mission
            )
            output_index += 1
            if step == steps:
                break

        heat_capacity = _heat_capacity(temperature, material)
        conductivity_scale = np.clip(
            1.0 - material.conductivity_damage_loss * damage, 0.45, 1.0
        )
        conductivity_z = material.conductivity_axial * conductivity_scale
        conductivity_x = material.conductivity_through * conductivity_scale
        heat_divergence = _conservative_diffusion(
            temperature, conductivity_z, conductivity_x, dz, dx
        )

        surface_temperature = temperature[:, 0]
        incident_heat = _surface_heat_flux(time_value, z, mission, grid)
        radiation = material.emissivity * _STEFAN_BOLTZMANN * (
            surface_temperature**4 - mission.ambient_temperature**4
        )
        heat_divergence[:, 0] += (incident_heat - radiation) / dx
        heat_divergence[:, -1] -= (
            mission.back_heat_transfer
            * (temperature[:, -1] - mission.support_temperature)
            / dx
        )

        reaction = oxidation_rate(temperature, oxidant, damage, oxidation)
        temperature_tendency = (
            heat_divergence + oxidation.reaction_heat_per_damage * reaction
        ) / (material.density * heat_capacity)

        effective_diffusivity = oxidation.oxidant_diffusivity * (
            1.0 + oxidation.damage_diffusivity_gain * damage
        )
        oxidant_tendency = _conservative_diffusion(
            oxidant, effective_diffusivity, effective_diffusivity, dz, dx
        )
        external_oxidant = _external_oxidant(time_value, mission)
        oxidant_tendency[:, 0] += (
            oxidation.surface_mass_transfer * (external_oxidant - oxidant[:, 0]) / dx
        )
        oxidant_tendency -= oxidation.oxidant_consumption * reaction

        temperature = temperature + grid.time_step * temperature_tendency
        oxidant = np.clip(oxidant + grid.time_step * oxidant_tendency, 0.0, 1.2)
        damage = np.clip(damage + grid.time_step * reaction, 0.0, 0.95)

        if not (
            np.all(np.isfinite(temperature))
            and np.all(np.isfinite(oxidant))
            and np.all(np.isfinite(damage))
        ):
            raise RuntimeError("TPS integration produced a non-finite state")

    return TPSFieldTrajectory(
        t=times,
        z=z,
        x=x,
        states=state_history,
        loads={
            "surface_heat_flux": surface_heat_history,
            "external_oxidant": external_oxidant_history,
        },
        mission_id=mission_id,
    )


def oxidation_rate(
    temperature: np.ndarray,
    oxidant: np.ndarray,
    damage: np.ndarray,
    parameters: TPSOxidation | None = None,
) -> np.ndarray:
    """Evaluate the hidden nonlinear carbon-consumption mechanism."""

    parameters = TPSOxidation() if parameters is None else parameters
    safe_temperature = np.maximum(np.asarray(temperature, dtype=float), 1.0)
    safe_oxidant = np.maximum(np.asarray(oxidant, dtype=float), 0.0)
    remaining_carbon = np.clip(1.0 - np.asarray(damage, dtype=float), 0.0, 1.0)
    return (
        parameters.pre_exponential
        * np.exp(
            -parameters.activation_energy / (_GAS_CONSTANT * safe_temperature)
        )
        * safe_oxidant**parameters.oxygen_exponent
        * remaining_carbon**parameters.remaining_carbon_exponent
    )


def reusable_tps_evaluation_truth(
    *,
    material: TPSMaterial | None = None,
    oxidation: TPSOxidation | None = None,
) -> dict[str, object]:
    """Return hidden metadata for post-discovery evaluation only."""

    material = TPSMaterial() if material is None else material
    oxidation = TPSOxidation() if oxidation is None else oxidation
    return {
        "shared_hidden_mechanism": (
            "A*exp(-Ea/(R*T))*O^m*(1-D)^q"
        ),
        "destinations": {
            "temperature": "positive reaction heat",
            "oxidant": "negative consumption",
            "damage": "positive carbon loss",
        },
        "oxidation": asdict(oxidation),
        "material": asdict(material),
        "secondary_feedbacks": (
            "damage-dependent conductivity",
            "damage-dependent oxidant diffusivity",
        ),
    }


def _surface_heat_flux(
    time_value: float,
    z: np.ndarray,
    mission: TPSMission,
    grid: TPSGrid,
) -> np.ndarray:
    temporal = np.exp(-0.5 * ((time_value - mission.peak_time) / mission.heat_width) ** 2)
    normalized_z = z / grid.axial_length
    spatial = 0.72 + 0.28 * np.exp(
        -0.5 * ((normalized_z - mission.hotspot_location) / mission.hotspot_width) ** 2
    )
    return mission.peak_heat_flux * temporal * spatial


def _external_oxidant(time_value: float, mission: TPSMission) -> float:
    return float(
        mission.peak_oxidant_activity
        * np.exp(-0.5 * ((time_value - mission.peak_time) / mission.oxidant_width) ** 2)
    )


def _heat_capacity(temperature: np.ndarray, material: TPSMaterial) -> np.ndarray:
    fraction = np.clip((temperature - 293.15) / (1873.15 - 293.15), 0.0, 1.0)
    return material.heat_capacity_ambient + fraction * (
        material.heat_capacity_hot - material.heat_capacity_ambient
    )


def _conservative_diffusion(
    field: np.ndarray,
    coefficient_z: np.ndarray,
    coefficient_x: np.ndarray,
    dz: float,
    dx: float,
) -> np.ndarray:
    """Cell-centred variable-coefficient diffusion with insulated side faces."""

    tendency = np.zeros_like(field)
    coefficient_z_face = 0.5 * (coefficient_z[1:, :] + coefficient_z[:-1, :])
    flux_z = -coefficient_z_face * (field[1:, :] - field[:-1, :]) / dz
    tendency[:-1, :] -= flux_z / dz
    tendency[1:, :] += flux_z / dz

    coefficient_x_face = 0.5 * (coefficient_x[:, 1:] + coefficient_x[:, :-1])
    flux_x = -coefficient_x_face * (field[:, 1:] - field[:, :-1]) / dx
    tendency[:, :-1] -= flux_x / dx
    tendency[:, 1:] += flux_x / dx
    return tendency


def _initial_damage_field(value: float | np.ndarray, shape: tuple[int, int]) -> np.ndarray:
    damage = np.asarray(value, dtype=float)
    if damage.ndim == 0:
        damage = np.full(shape, float(damage), dtype=float)
    if damage.shape != shape:
        raise ValueError(f"initial_damage must be scalar or have shape {shape}")
    if not np.all(np.isfinite(damage)) or np.any((damage < 0.0) | (damage >= 0.95)):
        raise ValueError("initial_damage must be finite and lie in [0, 0.95)")
    return np.array(damage, copy=True)


def _validate_configuration(
    mission: TPSMission,
    material: TPSMaterial,
    oxidation: TPSOxidation,
    grid: TPSGrid,
) -> None:
    numeric_values = [
        *asdict(mission).values(),
        *asdict(material).values(),
        *asdict(oxidation).values(),
        *asdict(grid).values(),
    ]
    if not all(np.isfinite(float(value)) for value in numeric_values):
        raise ValueError("all TPS configuration values must be finite")
    if mission.duration <= 0.0 or mission.peak_heat_flux < 0.0:
        raise ValueError("mission duration must be positive and heat flux non-negative")
    if not 0.0 < mission.peak_time < mission.duration:
        raise ValueError("peak_time must lie inside the mission")
    if mission.heat_width <= 0.0 or mission.oxidant_width <= 0.0:
        raise ValueError("mission widths must be positive")
    if material.density <= 0.0 or material.heat_capacity_ambient <= 0.0:
        raise ValueError("material density and heat capacity must be positive")
    if material.conductivity_axial <= 0.0 or material.conductivity_through <= 0.0:
        raise ValueError("material conductivities must be positive")
    if oxidation.activation_energy <= 0.0 or oxidation.pre_exponential < 0.0:
        raise ValueError("oxidation kinetics must be non-negative")
    if oxidation.oxidant_diffusivity <= 0.0:
        raise ValueError("oxidant_diffusivity must be positive")
    if grid.axial_cells < 3 or grid.thickness_cells < 3:
        raise ValueError("TPS grid must have at least three cells per direction")
    if grid.time_step <= 0.0 or grid.output_interval <= 0.0:
        raise ValueError("time steps and output interval must be positive")

    dx = grid.thickness / grid.thickness_cells
    dz = grid.axial_length / grid.axial_cells
    maximum_thermal_diffusivity_x = (
        material.conductivity_through
        / (material.density * material.heat_capacity_ambient)
    )
    maximum_thermal_diffusivity_z = (
        material.conductivity_axial
        / (material.density * material.heat_capacity_ambient)
    )
    explicit_number = grid.time_step * (
        maximum_thermal_diffusivity_x / dx**2
        + maximum_thermal_diffusivity_z / dz**2
    )
    if explicit_number >= 0.5:
        raise ValueError(
            "time_step violates the explicit thermal diffusion stability bound"
        )


def _readonly(values: np.ndarray) -> np.ndarray:
    array = np.array(values, copy=True)
    array.setflags(write=False)
    return array
